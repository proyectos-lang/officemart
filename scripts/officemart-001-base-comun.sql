-- -------------------------------------------------------------------------
-- 5. Limpieza de tesorería al borrar el padre: cadena por (fecha, id)
-- -------------------------------------------------------------------------
-- Mismo cuerpo que el script 039 de EasyCount, salvo el ORDER BY de la ventana:
-- desde ahora los movimientos pueden llevar fecha pasada, así que el saldo
-- corriente se acumula en orden cronológico y no en orden de inserción.
-- CREATE OR REPLACE conserva el OID: los triggers existentes siguen apuntando.
CREATE OR REPLACE FUNCTION officemart.tg_limpiar_tesoreria_ref()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = officemart
AS $$
DECLARE
  v_ref_tipo text := TG_ARGV[0];
  v_cuentas  bigint[];
BEGIN
  SELECT array_agg(DISTINCT cuenta_id::bigint) INTO v_cuentas
  FROM officemart.cuenta_movimientos
  WHERE ref_tipo = v_ref_tipo AND ref_id = OLD.id;

  DELETE FROM officemart.caja_chica_movimientos
  WHERE ref_tipo = v_ref_tipo AND ref_id = OLD.id;

  DELETE FROM officemart.cuenta_movimientos
  WHERE ref_tipo = v_ref_tipo AND ref_id = OLD.id;

  IF v_cuentas IS NOT NULL THEN
    WITH r AS (
      SELECT cm.id,
             SUM(CASE WHEN cm.tipo = 'Ingreso' THEN cm.monto ELSE -cm.monto END)
               OVER (PARTITION BY cm.cuenta_id ORDER BY cm.fecha, cm.id
                     ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS s
      FROM officemart.cuenta_movimientos cm
      WHERE cm.cuenta_id = ANY(v_cuentas)
    )
    UPDATE officemart.cuenta_movimientos cm
    SET saldo_resultante = ROUND(r.s, 2)
    FROM r
    WHERE cm.id = r.id
      AND cm.saldo_resultante IS DISTINCT FROM ROUND(r.s, 2);

    UPDATE officemart.cuentas_config c
    SET saldo = COALESCE((
      SELECT ROUND(SUM(CASE WHEN m.tipo = 'Ingreso' THEN m.monto ELSE -m.monto END), 2)
      FROM officemart.cuenta_movimientos m WHERE m.cuenta_id = c.id
    ), 0)
    WHERE c.id = ANY(v_cuentas);
  END IF;

  RETURN OLD;
END;
$$;

