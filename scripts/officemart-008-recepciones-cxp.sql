  ON officemart.compras_encabezado (razon_social_id, estado_recepcion);

-- -------------------------------------------------------------------------
-- 4. Kardex: qué recepción generó la entrada
-- -------------------------------------------------------------------------
ALTER TABLE officemart.transacciones_inventario ADD COLUMN IF NOT EXISTS recepcion_id bigint;

-- -------------------------------------------------------------------------
-- 5. Conceptos de gasto fuera del P&L (dato: "Compra de mercadería")
-- -------------------------------------------------------------------------
ALTER TABLE officemart.conceptos_gastos ADD COLUMN IF NOT EXISTS excluir_pyg boolean;
UPDATE officemart.conceptos_gastos
   SET excluir_pyg = true
 WHERE lower(nombre) IN ('compra de mercadería', 'compra de mercaderia')
   AND excluir_pyg IS DISTINCT FROM true;

-- -------------------------------------------------------------------------
-- 6. Incremento atómico de cantidad recibida (evita leer-modificar-escribir)
-- -------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION officemart.incrementar_cantidad_recibida(
  p_detalle_id bigint,
  p_delta      numeric
)
RETURNS numeric
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = officemart
AS $$
DECLARE
  v_nueva numeric;
BEGIN
  UPDATE officemart.compras_detalle
     SET cantidad_recibida = COALESCE(cantidad_recibida, 0) + COALESCE(p_delta, 0)
   WHERE id = p_detalle_id
     AND razon_social_id = officemart.app_current_tenant()
  RETURNING cantidad_recibida INTO v_nueva;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'DETALLE_NO_ENCONTRADO: linea % no existe o no es de la empresa', p_detalle_id;
  END IF;
  RETURN v_nueva;
END;
$$;
REVOKE ALL ON FUNCTION officemart.incrementar_cantidad_recibida(bigint, numeric) FROM public;
GRANT EXECUTE ON FUNCTION officemart.incrementar_cantidad_recibida(bigint, numeric) TO authenticated;

