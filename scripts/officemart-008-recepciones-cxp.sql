ALTER TABLE officemart.compras_encabezado ADD COLUMN IF NOT EXISTS forma_pago            text;      -- 'Contado' | 'Credito'
ALTER TABLE officemart.compras_encabezado ADD COLUMN IF NOT EXISTS dias_credito          integer;
ALTER TABLE officemart.compras_encabezado ADD COLUMN IF NOT EXISTS fecha_vencimiento     date;
ALTER TABLE officemart.compras_encabezado ADD COLUMN IF NOT EXISTS monto_pagado          numeric;
ALTER TABLE officemart.compras_encabezado ADD COLUMN IF NOT EXISTS estado_pago           text;      -- 'Pendiente' | 'Parcial' | 'Pagado'
ALTER TABLE officemart.compras_encabezado ADD COLUMN IF NOT EXISTS total_recibido_local  numeric;   -- suma de recepciones (L)
