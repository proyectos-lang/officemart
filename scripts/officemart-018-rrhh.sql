  dias_periodo       numeric(6,2)  NOT NULL DEFAULT 0,
  dias_no_pagados    numeric(6,2)  NOT NULL DEFAULT 0,
  salario_periodo    numeric(14,2) NOT NULL DEFAULT 0,
  horas_extra        numeric(14,2) NOT NULL DEFAULT 0,
