  gasto_id           bigint,
  notas              text,
  aprobada_at        timestamptz,
  pagada_at          timestamptz,
  anulada_at         timestamptz,
  motivo_anulacion   text,
  usuario            text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz
