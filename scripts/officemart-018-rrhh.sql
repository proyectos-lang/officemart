CREATE TABLE IF NOT EXISTS officemart.rrhh_nominas (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  razon_social_id    bigint  NOT NULL,
  tipo               text    NOT NULL DEFAULT 'Mensual',   -- Mensual | Quincenal
  periodo_desde      date    NOT NULL,
  periodo_hasta      date    NOT NULL,
  fecha_pago         date,
  estado             text    NOT NULL DEFAULT 'Borrador',  -- Borrador | Aprobada | Pagada | Anulada
  total_devengado    numeric(14,2) NOT NULL DEFAULT 0,
  total_deducciones  numeric(14,2) NOT NULL DEFAULT 0,
  total_neto         numeric(14,2) NOT NULL DEFAULT 0,
  total_patronal     numeric(14,2) NOT NULL DEFAULT 0,
